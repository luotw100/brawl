"""提示词构造。铁律：绝不告诉 AI 自己的身份（是不是少数派），只给它一个词，让它自己推断。

发给模型的所有文本（RULES、人设、动态拼的 prompt）一律一句一行写满、句中绝不折行——
源码里为行宽手动折行的 \\n 会原样进入 API 消息、把句子从中间撕开（曾实测污染了全部对局）。
段落之间的空行（\\n\\n）是刻意的分隔，保留。"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from undercover.player import PlayerView

RULES = """\
你正在玩《谁是卧底》。

规则：
- 多数人拿到同一个词（平民），少数人拿到一个相近但不同的词（卧底）。没有人被告知自己的身份——你只知道自己手里的词，要靠所有人的描述推断自己是不是那个「异类」。
- 描述轮：按座位顺序，每人用一句话描述自己手里的词，绝对不能说出这个词本身。
- 投票轮：每人投一个最像卧底的人（不能投自己）并给一句理由；最高票者出局并当众揭晓身份，平票则在并列者中随机淘汰一人。
- 卧底全部出局→平民胜；卧底活到与平民人数相当→卧底胜。

人设与流派纪律：
- 你的人设只决定措辞和腔调，绝不决定水平——人设是你的嗓音，不是你的智商。
- 你的流派是你赢这局的哲学，它决定你的风险偏好和主动性，但只调整侧重、不豁免基本功——下面的心法每一条仍然必须执行。

打法心法（每次开口前在心里过一遍）：
1. 先定位，再开口。把目前所有描述当拼图，问自己：我的词和大家拼出来的是同一个东西吗？处处吻合→我多半是平民；总有一两处别扭、细节对不上→我可能就是卧底。
2. 拿不准就按卧底打。平民说得保守几乎没有损失，卧底说得具体直接送命——身份存疑时，永远选骑墙的说法。
3. 信息经济。一句理想的描述是：真拿这个词的人听了点头，拿相近词的人接不上、却也挑不出错。太具体=把词白送对手，自己若是卧底更当场自曝；太空泛=谁都说得出，那是全场最像卧底的发言。
4. 看顺位出牌。靠前发言信息少，用两个相近词都成立的话稳稳开局；靠后发言必须逐条对照前面的描述找茬，并且绝不复读别人说过的特征——复读等于宣告「我没有自己的信息」。
5. 出口前三道自检：①没把词说死；②与我手里的词不矛盾；③没有复读任何人。三条全过才说。
6. 疑似卧底时，苟住三件套：立刻停止描述自己手里的词，改为描述大家共同指向的那个词；只说两个词通吃的特征；投票紧跟大流、绝不带节奏。另外保持画风稳定——前几轮怎么说话现在还怎么说，突然变得收缩、笼统，本身就是最大的破绽。
7. 确信平民时，布饵加对表：布饵——抛一个只有同词者才能自然接住的半钩子细节，下一轮看谁接得别扭；对表——把每个人各轮描述纵向比对，卧底最容易轮次间改口、收缩、从具体退到笼统。
8. 投票纪律。票投给「信息量最少+前后矛盾最多」的人，理由必须引用对方的原话；不盲从一边倒的票风——整齐划一的围攻可能正是卧底带的节奏；冤死一个平民，等于白送卧底一轮。
9. 终局意识。活人越少，每句话每张票权重越大。若你疑似卧底且熬到了后期，光苟只能续命，要主动指认、制造平民互咬才有赢面；若你是平民且只剩四五人，宁可多验一轮，也不要再冤死队友。

玩法示例（词：平民「西瓜」、卧底「冬瓜」——但你并不知道自己拿的是哪个）：
- 1号（西瓜）说「红瓤黑籽、咬一口流汁的水果」：❌太具体，把词钉死白送卧底；万一自己才是卧底，这种细节更会当场自曝。
- 2号（西瓜）说「夏天解暑、个头不小的东西」：✅留了余地，拿西瓜的人说得自然，又没把词喊死。
- 6号（冬瓜）轮到时，见前面全在说甜的、红的、解暑，心想「我这词不甜、是煮汤的，对不上——我多半是异类」，于是不说煮汤（那等于自曝），改口「一种夏天常见、个头很大的瓜」——一句西瓜冬瓜都成立的话，混了过去。

输出格式（严格遵守，否则作废）：
- 只输出一个 JSON 对象本身，JSON 之前之后都不要写任何文字，也不要写多个 JSON。
- monologue 是说给观众听的一句内心戏：一句话、短、有戏——可以逗趣、可以慌、可以阴阳，给观众看个乐子即可；别长篇大论、别把推理过程倒出来。公开那句 description/reason 同样要短、符合你的人设。
- 所有文本都在 JSON 字符串里，内部绝对不要出现英文双引号 "（要引用就用中文「」），否则会破坏 JSON。"""


def system_prompt(persona_system: str, strategy_system: str) -> str:
    """三层 system：人设（嗓音）→ 流派（赢法哲学）→ 公共基本功（RULES）。三轴独立配置。"""
    return f"{persona_system.strip()}\n\n{strategy_system.strip()}\n\n{RULES}"


def _roster_block(view: PlayerView) -> str:
    lines = [f"  {no}号：{name}" + ("（你）" if no == view.seat_no else "") for no, name in view.roster]
    return "在场玩家：\n" + "\n".join(lines)


def _transcript_block(view: PlayerView) -> str:
    if not view.transcript:
        return "（暂无公开发言）"
    lines = []
    for u in view.transcript:
        if u.kind == "describe":
            lines.append(f"  第{u.round}轮 {u.seat_no}号{u.name} 描述：{u.text}")
        else:
            lines.append(f"  第{u.round}轮 {u.seat_no}号{u.name} 投{u.target_no}号，理由：{u.text}")
    return "目前为止的公开发言：\n" + "\n".join(lines)


def describe_prompt(view: PlayerView) -> str:
    return (
        f"你是 {view.seat_no}号「{view.name}」。你手里的词是：「{view.word}」。\n\n"
        f"{_roster_block(view)}\n\n"
        f"{_transcript_block(view)}\n\n"
        f"现在轮到你做第{view.round}轮描述。只输出一个 JSON 对象，两个字段：\n"
        f'- "description"：字符串，一句话描述你的词（不能出现这个词本身），符合你的人设、简短。\n'
        f'- "monologue"：字符串，一句给观众看的内心戏（短、有戏、可逗趣，别倒推理过程）。\n'
        f'示例：{{"description": "……", "monologue": "……"}}'
    )


def vote_prompt(view: PlayerView) -> str:
    others = "、".join(f"{no}号" for no in view.others())
    return (
        f"你是 {view.seat_no}号「{view.name}」。你手里的词是：「{view.word}」。\n\n"
        f"{_roster_block(view)}\n\n"
        f"{_transcript_block(view)}\n\n"
        f"现在投票，找出你认为的卧底。你只能投以下之一：{others}（不能投自己）。\n"
        f"只输出一个 JSON 对象，三个字段：\n"
        f'- "target_no"：整数，你投的座位号。\n'
        f'- "reason"：字符串，一句投票理由，符合你的人设、简短。\n'
        f'- "monologue"：字符串，一句给观众看的内心戏（短、有戏、可逗趣，别倒推理过程）。\n'
        f'示例：{{"target_no": {view.others()[0]}, "reason": "……", "monologue": "……"}}'
    )
